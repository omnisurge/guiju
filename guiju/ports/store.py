"""Store 端口：应用层只依赖这里的行为，不依赖 sqlite 适配器。"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol


class StorePort(Protocol):
    """应用层使用的最小存储契约；实现见 adapters.store.sqlite。"""

    path: Path
    schema_version: int

    def probe_counts(self) -> dict[str, int]: ...

    def stats(self) -> dict[str, Any]: ...

    def get_ann(self, ann_id: int) -> dict[str, Any] | None: ...

    def get_ann_by_url(self, url: str) -> dict[str, Any] | None: ...

    def upsert_announcement(
        self, url: str, published_on: str, title: str, doc_name: str, category: str
    ) -> tuple[int, bool]: ...

    def catalog_entries(self, *args: Any, **kwargs: Any) -> list[dict[str, Any]]: ...

    def find_by_code(self, *args: Any, **kwargs: Any) -> list[dict[str, Any]]: ...

    def mentions_for(self, ann_id: int) -> list[dict[str, Any]]: ...

    def persist_codes(self, ann_id: int, codes: Any, doc_name: str, status: str | None = None) -> None: ...

    def source_meta(self, source: str) -> dict[str, Any]: ...

    def catalog_meta_corrupt(self, source: str) -> str | None: ...

    def catalog_age_days(self, source: str = "mohurd") -> float | None: ...

    def count_announcements(self) -> int: ...

    def max_published_on(self) -> str | None: ...

    def log_probe(self, *args: Any, **kwargs: Any) -> None: ...

    def commit(self) -> None: ...

    def close(self) -> None: ...
